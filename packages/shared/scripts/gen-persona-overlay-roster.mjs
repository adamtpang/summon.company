// Generate packages/shared/src/persona-overlay-roster.generated.ts from the
// picker's slug source of truth (ui/src/lib/personas.ts). Run from repo root:
//   node packages/shared/scripts/gen-persona-overlay-roster.mjs
//
// SUM-253: the runtime overlay resolver (persona-overlay.ts) needs a
// server-importable slug -> archetype roster. ui/src/lib/personas.ts is
// UI-only and itself generated (ui/scripts/gen-personas.py from
// company/<dept>/persona.json). Rather than hand-maintain a third copy, we
// mechanically derive this shared roster from personas.ts so there is exactly
// one authoring source. Regenerate after editing the picker roster.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..", "..");
const personasTsPath = path.join(repoRoot, "ui", "src", "lib", "personas.ts");
const outPath = path.join(here, "..", "src", "persona-overlay-roster.generated.ts");

const src = fs.readFileSync(personasTsPath, "utf8");
const marker = "export const PERSONAS";
const markerIndex = src.indexOf(marker);
if (markerIndex < 0) throw new Error(`Could not find ${marker} in ${personasTsPath}`);
const arrayStart = src.indexOf("= [", markerIndex) + 2;

let depth = 0;
let arrayEnd = -1;
for (let i = arrayStart; i < src.length; i++) {
  const ch = src[i];
  if (ch === "[") depth++;
  else if (ch === "]") {
    depth--;
    if (depth === 0) {
      arrayEnd = i;
      break;
    }
  }
}
if (arrayEnd < 0) throw new Error("Could not bracket-match the PERSONAS array literal");

// The literal is JSON-with-double-quotes; eval it in a sandboxed function.
// eslint-disable-next-line no-new-func
const personas = Function(`"use strict";return (${src.slice(arrayStart, arrayEnd + 1)});`)();

// Keep only the fields the runtime overlay needs. Drop UI-only noise.
const roster = personas.map((p) => ({
  slug: p.slug,
  archetype: p.archetype,
  department: p.department,
  title: p.title,
  lifespan: p.lifespan,
  oneLiner: p.oneLiner,
  principles: p.principles,
  quote: p.quote ? { text: p.quote.text, source: p.quote.source } : null,
  isDefault: Boolean(p.isDefault),
}));

const banner = `// AUTO-GENERATED by packages/shared/scripts/gen-persona-overlay-roster.mjs — DO NOT EDIT BY HAND.
// Source of truth: ui/src/lib/personas.ts (the persona picker roster, SUM-196).
// Regenerate: node packages/shared/scripts/gen-persona-overlay-roster.mjs
`;

const body = `${banner}
import type { PersonaOverlay } from "./persona-overlay.js";

export const PERSONA_OVERLAY_ROSTER: readonly PersonaOverlay[] = ${JSON.stringify(roster, null, 2)} as const;
`;

fs.writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${roster.length} personas to ${path.relative(repoRoot, outPath)}`);
